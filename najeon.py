# (a) COLOR PALETTE FUNCTION
# ==========================================
def get_najeon_palette(num_colors=6):
    """
    Generates a random palette of shimmering mother-of-pearl (Najeon) hues:
    soft iridescence (pinks, teals, lavenders, mints, and pearl creams).
    Returns colors as hex codes.
    """
    palette = []
    for _ in range(num_colors):
        hue_choice = random.choice(["teal_green", "pink_violet", "pearl_cream"])

        if hue_choice == "teal_green":
            r, g, b = random.randint(80, 160), random.randint(200, 255), random.randint(200, 245)
        elif hue_choice == "pink_violet":
            r, g, b = random.randint(210, 255), random.randint(140, 200), random.randint(210, 255)
        else:  # pearl_cream
            r, g, b = random.randint(230, 250), random.randint(235, 255), random.randint(220, 245)

        palette.append(f"#{r:02x}{g:02x}{b:02x}") # Return hex
    return palette

# Utility functions for color manipulation
def hex_to_rgb(hex_color):
    hex_color = hex_color.lstrip('#')
    return tuple(int(hex_color[i:i+2], 16) for i in (0, 2, 4))

def rgb_to_hex(rgb_tuple):
    return f"#{rgb_tuple[0]:02x}{rgb_tuple[1]:02x}{rgb_tuple[2]:02x}"

def adjust_brightness(hex_color, factor): # factor > 1 to lighten, < 1 to darken
    rgb = hex_to_rgb(hex_color)
    new_rgb = tuple(min(255, max(0, int(c * factor))) for c in rgb)
    return rgb_to_hex(new_rgb)


